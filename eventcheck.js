
const g=require('./harness.js');
const N=+process.argv[2]||300,bot=process.argv[3]||'budget';
const bySit={},titles=new Set(),seqs=new Set(),perTerm=[],genShare=[],samples=[];let errs=0,roundtrip=0,afterSeen=0,lastGE=null;
for(let n=0;n<N;n++){g.setSeed(1000+n*7919);const S=g.SIM;S.me=3;S.pledge=2;S.polls=[];
 try{g.startGov(true)}catch(e){errs++;console.error('start',e.message);continue}
 const G=S.gov;let guard=0,ids=[],gen=0,tot=0;
 while(G.q<16&&!G.fell&&guard++<60){if(G.q===0)g.autoCab();
  if(bot==='budget'&&G.q%4===0){const B=[62,25,13,22,12,8,4,14.5];g.st.bud=B.map(v=>+(v*(0.75+Math.random()*0.6)).toFixed(1))}
  G.pend.forEach(p=>{const e=g.GE[p.i];tot++;const id=String(e[6]);ids.push(id);if(id.startsWith('g_')){gen++;const k=id.split('_').slice(1,2)[0];bySit[k]=(bySit[k]||0)+1;titles.add(e[0]);if(k==='after')afterSeen++;if(samples.length<14&&Math.random()<.04)samples.push(e[0]+' — '+e[2]+' ['+e[4].map(o=>o.f).join(' / ')+']')}});
  try{let k=0;while(G.pend.length&&k++<10){const o=g.GE[G.pend[0].i][4];g.resolveGE(0,(Math.random()*o.length)|0)}}catch(e){errs++;console.error('resolve',e.message);break}
  if(G.offer&&G.offer.length&&!(G.vote&&!G.vote.done)){try{g.tableBill(0);if(G.vote&&!G.vote.done)g.finishVote()}catch(e){}}
  if(g.isBudQ(G.q)&&!G.bdone){try{g.bvote();if(G.vote&&!G.vote.done)g.finishVote()}catch(e){}}
  if(G.fell)break;try{g.endQuarter()}catch(e){errs++;console.error('EQ',e.message);break}}
 // save/load safety: generated events must survive JSON
 const gens=g.GE.filter(e=>String(e[6]).startsWith('g_'));try{const back=JSON.parse(JSON.stringify(gens));if(back.length===gens.length&&back.every((e,i)=>e[0]===gens[i][0]&&e[4].length===gens[i][4].length))roundtrip++}catch(e){}
 seqs.add(ids.join(','));perTerm.push(tot);genShare.push(tot?gen/tot:0);lastGE=g.GE.length}
const avg=a=>a.reduce((x,y)=>x+y,0)/(a.length||1);
console.log('terms',N,'| errors',errs,'| JSON roundtrip ok',roundtrip+'/'+N);
console.log('events/term',avg(perTerm).toFixed(1),'| generated share',(avg(genShare)*100).toFixed(0)+'%','| distinct generated titles',titles.size,'| unique sequences',seqs.size+'/'+N);
console.log('generated by situation:',JSON.stringify(bySit),'| aftermath chains seen',afterSeen);
console.log('GE length after last term (should be ~ static+gen of one term):',lastGE);
console.log('\nSAMPLES:');samples.forEach(s=>console.log(' •',s));
